print(f'\nShape after dropping high-missing columns: {df.shape}')

"""### 3.4 — Remove Post-Incident Outcome Variables

Our model will predict **severity before an attack occurs**, so we must exclude all columns that represent outcomes measured **after** the event. We temporarily retain `nkill` to build the target variable, then remove it.
"""

# Post-incident outcome columns to exclude.
# nkill is kept temporarily for target creation and removed afterward.
