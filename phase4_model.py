missing_df[missing_df['Missing %'] > 0].head(30)

"""### 3.3 — Drop Columns with >70% Missing Values

Columns where more than 70% of values are missing carry too little information to be useful and are removed.
"""

# Identify columns exceeding the 70% missing threshold
