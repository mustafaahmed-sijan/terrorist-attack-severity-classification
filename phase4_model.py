"""---
## Section 12 — Standardized Model Evaluation Framework

We implement `evaluate_model` to compute **Macro F1**, **Weighted F1**, **Accuracy**, and display the confusion matrix.
"""

def evaluate_model(model, X_eval, y_eval, model_name='Model'):
    """
    Standardized evaluation printing metrics and plotting confusion matrix.
    """
    y_pred = model.predict(X_eval)

    acc = accuracy_score(y_eval, y_pred)
    f1_macro = f1_score(y_eval, y_pred, average='macro')
    f1_weighted = f1_score(y_eval, y_pred, average='weighted')
    prec_macro = precision_score(y_eval, y_pred, average='macro')
    rec_macro = recall_score(y_eval, y_pred, average='macro')

    print(f'\n{"="*65}')
    print(f'  {model_name.upper()} — TEST SET RESULTS')
    print(f'{"="*65}')
    print(f'  Accuracy        : {acc:.4f} ({acc*100:.2f}%)')
    print(f'  Macro F1-Score  : {f1_macro:.4f}  <-- Primary Metric')
    print(f'  Weighted F1     : {f1_weighted:.4f}')
    print(f'  Macro Precision : {prec_macro:.4f}')
    print(f'  Macro Recall    : {rec_macro:.4f}')
    print(f'{"="*65}')

    print('\nClassification Report:')
    print(classification_report(y_eval, y_pred, target_names=TARGET_NAMES, digits=4))

    fig, ax = plt.subplots(figsize=(6, 5))
    cm = confusion_matrix(y_eval, y_pred)
    disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=TARGET_NAMES)
    disp.plot(cmap='Blues', ax=ax, values_format=',d')
    ax.set_title(f'{model_name} — Confusion Matrix', fontsize=12, fontweight='bold')
    plt.tight_layout()
    plt.show()

    return {
        'Model': model_name,
        'Accuracy': round(acc, 4),
        'Macro F1': round(f1_macro, 4),
        'Weighted F1': round(f1_weighted, 4),
        'Macro Precision': round(prec_macro, 4),
        'Macro Recall': round(rec_macro, 4)
    }

