"""### 3.7 — Impute Remaining Missing Values

- **Categorical columns** → fill with the **mode** (most frequent value)  
- **Numerical columns** → fill with the **median** (robust to outliers)  
- Rows with a missing `nkill` are dropped since we need it to define the target.
"""

# Drop rows where nkill is missing — required for target variable creation
before = len(df)
df.dropna(subset=['nkill'], inplace=True)
df.reset_index(drop=True, inplace=True)
after = len(df)
print(f'Rows dropped due to missing nkill: {before - after:,}')
print(f'Remaining rows: {after:,}')

# Separate columns by type
cat_cols = df.select_dtypes(include=['object', 'category']).columns.tolist()
num_cols = df.select_dtypes(include=['number']).columns.tolist()

# Impute categorical columns with mode
for col in cat_cols:
    if df[col].isnull().sum() > 0:
        mode_val = df[col].mode()[0]
        df[col].fillna(mode_val, inplace=True)

# Impute numerical columns with median (exclude nkill — handled separately)
for col in num_cols:
    if col == 'nkill':
        continue
    if df[col].isnull().sum() > 0:
        median_val = df[col].median()
        df[col].fillna(median_val, inplace=True)

# Confirm no missing values remain
remaining_missing = df.isnull().sum().sum()
print(f'Total missing values after imputation: {remaining_missing}')
print(f'Final shape: {df.shape}')

"""---
## Section 4 — Target Variable: Severity

We create a four-class ordinal target variable based on the number of fatalities (`nkill`):

| Fatalities | Severity Class |
|:-----------:|:--------------:|
| 0 | **None** |
| 1 – 2 | **Low** |
| 3 – 10 | **Medium** |
| > 10 | **High** |

After constructing the target, `nkill` is removed from the feature set.
"""

def assign_severity(kills):
    """Map fatality count to a severity category."""
    if kills == 0:
        return 'None'
    elif kills <= 2:
        return 'Low'
    elif kills <= 10:
        return 'Medium'
    else:
        return 'High'

# Apply the mapping
df['Severity'] = df['nkill'].apply(assign_severity)

# Define natural ordinal ordering
severity_order = ['None', 'Low', 'Medium', 'High']
df['Severity'] = pd.Categorical(df['Severity'], categories=severity_order, ordered=True)

